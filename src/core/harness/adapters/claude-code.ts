import path from 'path';
import { NeutralAgentDef, GeneratedFile } from '../types.js';
import { HarnessAdapter, resolveTools } from './types.js';

const DEFAULT_MODEL = 'claude-sonnet-4-6';

function memoryPreamble(memoryPath: string): string {
  return `## Memory Access

Business rules, features, and test conventions are stored in \`${memoryPath}/\`.
Before drafting, use the **Read** tool to load them.

- \`${memoryPath}/rules.md\` — business rules
- \`${memoryPath}/features.md\` — product features
- \`${memoryPath}/conventions.md\` — test conventions

Read all three files before generating test cases. If they are empty or missing, draft from the feature description alone.

---

`;
}

function generateAgentFile(def: NeutralAgentDef): string {
  const model =
    def.models['claude'] ??
    def.models['claude-code'] ??
    DEFAULT_MODEL;

  const nativeTools = resolveTools(def.tools, 'claude-code');

  const frontmatter = [
    '---',
    `name: ${def.name}`,
    `description: ${def.description}`,
    `model: ${model}`,
    `tools: [${nativeTools.join(', ')}]`,
    '---',
  ].join('\n');

  const warning = `<!-- Generated by qai harness v${def.version} — do not edit directly. Edit agents/${def.name}.md and re-run: qai harness generate --provider claude-code -->`;

  return [frontmatter, '', warning, '', memoryPreamble(def.memoryPath), def.systemPrompt].join('\n');
}

export class ClaudeCodeAdapter implements HarnessAdapter {
  readonly providerTarget = 'claude-code' as const;

  generate(defs: NeutralAgentDef[], _projectRoot: string): GeneratedFile[] {
    return defs.map((def) => ({
      path: path.join('.claude', 'agents', `${def.name}.md`),
      content: generateAgentFile(def),
    }));
  }
}
